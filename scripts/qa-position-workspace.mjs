import { chromium, expect } from '@playwright/test';
import assert from 'node:assert/strict';
import { readFileSync, mkdirSync } from 'node:fs';
mkdirSync('.local/qa', { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1080 } });
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto('http://localhost:8982/admin');
  await page.getByLabel('管理员密码').fill(readFileSync('.local/admin-access.txt', 'utf8').match(/^Password: (.+)$/m)[1]);
  await page.getByRole('button', { name: '进入工作台', exact: true }).click();
  await page.getByRole('button', { name: '保存草稿', exact: true }).waitFor();
  const before = await page.request.get('http://localhost:8982/api/admin').then(r => r.json());
  const state = structuredClone(before), t = state.templates[0].draft;
  const frame = t.nodes.find(n => n.id === '5-0'), code = t.nodes.find(n => n.role === 'wechat');
  code.x = frame.x + frame.width - 120; code.width = code.height = 240;
  await page.route('**/api/admin', async route => {
    assert.equal(route.request().method(), 'GET', 'QA does not write the saved draft');
    await route.fulfill({ json: state });
  });
  await page.reload();
  await page.getByRole('button', { name: '三码放置区域', exact: true }).click();
  const canvas = page.getByRole('img', { name: '图层位置实时预览', exact: true });
  await expect(canvas).toHaveAttribute('data-position', /^5-1:/);
  await expect(page.locator('.position-preview-warning')).toHaveCount(0);
  const visiblePixels = () => canvas.evaluate(c => {
    const pixels = c.getContext('2d').getImageData(0, 0, c.width, c.height).data;
    let count = 0; for (let i = 3; i < pixels.length; i += 4) if (pixels[i]) count++;
    return count;
  });
  assert.ok(await visiblePixels() > 100000, 'the complete preview is painted despite overflow');
  const previewBox = await canvas.boundingBox(), controlBox = await page.locator('.position-controls-panel').boundingBox();
  assert.ok(previewBox.x + previewBox.width <= controlBox.x);
  assert.ok(previewBox.y >= 0 && previewBox.y + previewBox.height <= 1080);
  await page.screenshot({ path: '.local/qa/position-overflow-visible.png' });
  await page.locator('.position-controls-panel').evaluate(el => el.scrollTop = el.scrollHeight);
  assert.deepEqual(await canvas.boundingBox(), previewBox, 'right-panel scrolling does not move preview');
  assert.equal(await page.evaluate(() => scrollY), 0);
  const beforeDrag = await canvas.getAttribute('data-size');
  const handle = page.getByRole('button', { name: '调整收款码大小（右下）', exact: true });
  const box = await handle.boundingBox();
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2); await page.mouse.down();
  await page.mouse.move(box.x + box.width / 2 - 12, box.y + box.height / 2 - 12, { steps: 5 }); await page.mouse.up();
  await expect.poll(() => canvas.getAttribute('data-size')).not.toBe(beforeDrag);
  assert.ok(await visiblePixels() > 100000);
  await page.getByRole('button', { name: '图层与权限', exact: true }).click();
  await page.getByRole('button', { name: 'PSD 根目录', exact: true }).click();
  await page.locator('.psd-folders').getByRole('button', { name: '微信', exact: true }).click();
  await page.locator('.layer-list button').filter({ has: page.locator('.layer-number', { hasText: /^5-1$/ }) }).click();
  await expect(canvas).toHaveAttribute('data-position', /^5-1:/);
  assert.ok(await visiblePixels() > 100000);
  const left = await canvas.boundingBox(), right = await page.locator('.position-controls-panel').boundingBox();
  assert.ok(left.x + left.width <= right.x);
  await page.locator('.position-controls-panel').evaluate(el => el.scrollTop = el.scrollHeight);
  assert.deepEqual(await canvas.boundingBox(), left);
  await page.screenshot({ path: '.local/qa/layers-split-preview.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.screenshot({ path: '.local/qa/position-mobile.png' });
  assert.deepEqual(errors, []);
  const after = await page.request.get('http://localhost:8982/api/admin').then(r => r.json());
  assert.deepEqual(after.templates, before.templates);
  console.log('Position workspace QA passed: overflow renders without warnings, drag works, left preview/right controls in both admin editors, independent scrolling, mobile, saved templates unchanged.');
} finally { await browser.close(); }
